    "          if isinstance(res, list):\n",
    "              for rec in res: fout.write(json.dumps(rec, ensure_ascii=False)+\"\\n\")\n",
    "              fckpt.write(f\"{idx}\\n\"); ok += 1\n",
    "          else:\n",
    "              err += 1\n",
    "              print(f\"row {idx} FAILED: {res}\")\n",
    "          if n % 100 == 0:\n",
    "              fout.flush(); fckpt.flush()\n",
    "              el = time.time()-t0\n",
    "              print(f\"{n}/{len(todo)} ok={ok} err={err} {el:.0f}s rate={n/el:.1f}/s\")\n",
    "  fout.flush(); fckpt.flush(); fout.close(); fckpt.close()\n",
    "  print(f\"DONE ok={ok} err={err} time={time.time()-t0:.0f}s\")\n",
    "\n",
    "if __name__ == \"__main__\":\n",
    "    main()"
