    "  print(f\"todo {len(todo)} / {len(df)}\")\n",
    "\n",
    "  fout = open(OUT, 'a')\n",
    "  fckpt = open(CKPT, 'a')\n",
    "  t0 = time.time()\n",
    "  ok = err = 0\n",
    "  with ThreadPoolExecutor(max_workers=12) as ex:\n",
