    "        j_title=trunc(row['jd_job_title']), j_min=trunc(row['jd_minimum_requirements']),\n",
    "        j_pref=trunc(row['jd_preferred_qualifications']), j_other=trunc(row['jd_other_information']))\n",
    "    last = None\n",
    "    for attempt in range(4):\n",
    "        try:\n",
    "            scores = call_api(prompt)\n",
    "            recs = []\n",
    "            for r in RS:\n",
    "                for j in JS:\n",
    "                    sc = float(scores[f\"{r}|{j}\"])\n",
    "                    sc = max(1.0, min(10.0, sc))\n",
    "                    recs.append({\n",
    "                        \"resume_id\": row['resume_resume_id'],\n",
    "                        \"jd_id\": row['jd_job_id'],\n",
    "                        \"resume_section_name\": r,\n",
    "                        \"jd_section_name\": j,\n",
    "                        \"resume_section_content\": row[r],\n",
    "                        \"jd_section_content\": row[j],\n",
    "                        \"matching_score\": sc})\n",
    "            return idx, recs\n",
    "        except Exception as e:\n",
    "            last = e\n",
    "            time.sleep(2*(attempt+1))\n",
    "    return idx, last\n",
